# cog-gen.ps1 -- MATERIALIZE one build cell (loader x Minecraft line) from the ONE edit surface (_codegen).
# Usage: pwsh -File scripts\cog-gen.ps1 -Loader Fabric -Line 26.2
#
# A cell dir (<Loader>/<line>/) is 100% disposable and gitignored. cog-gen wipes it and rebuilds the whole
# thing: build.gradle + settings.gradle + gradle.properties + the loader manifest + the gradle wrapper + the
# gen\ source tree. Per-cell values (pins, JDK, Gradle, pack_format, ranges) come from _codegen\matrix.json;
# the @TOKENS@ in _codegen\cell_templates\<Loader>\** are filled from it.
#
# D16: every Java file lives exactly ONCE under _codegen\cog_sources (common = MC-agnostic pure Java; shared =
# MC code with Cog markers at version-drift points; resources) or is emitted from _codegen\compat.py (the
# per-loader ENTRYPOINTS, D15).
param(
    [Parameter(Mandatory)][string]$Loader,   # Fabric | NeoForge | Forge
    [Parameter(Mandatory)][string]$Line      # 1.21.11 | 26.1 | 26.2 | 26.3 | 26.4
)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
$cg  = Join-Path $repoRoot '_codegen'
$cs  = Join-Path $cg 'cog_sources'
$matrix = Get-Content (Join-Path $cg 'matrix.json') -Raw | ConvertFrom-Json
$key = "$Loader/$Line"
$c = $matrix.cells.$key
if (-not $c) { throw "no matrix cell '$key' (see _codegen\matrix.json)" }
$lc  = $Loader.ToLower()
$cell = Join-Path (Join-Path $repoRoot $Loader) $Line
$ct   = Join-Path $cg (Join-Path 'cell_templates' $Loader)

# ---- token table ----
$tok = @{
    MOD_ID = $matrix.mod_id; MOD_VERSION = $matrix.mod_version
    MC = $c.mc; LINE = $c.line; JDK = $c.jdk
}
foreach ($p in $c.PSObject.Properties) { $tok[$p.Name.ToUpper()] = [string]$p.Value }
if ($Loader -eq 'Fabric') {
    if ($c.era -eq 'obf') {
        $tok['FABRIC_DEPS'] = "    mappings loom.officialMojangMappings()`n    modImplementation `"net.fabricmc:fabric-loader:`${project.loader_version}`"`n    modImplementation `"net.fabricmc.fabric-api:fabric-api:`${project.fabric_api_version}`""
    } else {
        $tok['FABRIC_DEPS'] = "    compileOnly localRuntime(`"net.fabricmc:fabric-loader:`${project.loader_version}`")`n    compileOnly localRuntime(`"net.fabricmc.fabric-api:fabric-api:`${project.fabric_api_version}`")"
    }
}
function Fill([string]$text) {
    foreach ($k in $tok.Keys) { $text = $text.Replace("@$k@", $tok[$k]) }
    if ($text -match '@[A-Z_]+@') { throw "unfilled token in cell template: $($Matches[0])" }
    return $text
}

# ---- 1. wipe the cell ----
Remove-Item $cell -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $cell | Out-Null

# ---- 2. build wiring + manifest from the cell template, tokens filled ----
Get-ChildItem $ct -Recurse -File | ForEach-Object {
    $rel  = $_.FullName.Substring($ct.Length).TrimStart('\')
    $dest = Join-Path $cell $rel
    New-Item -ItemType Directory -Force -Path (Split-Path $dest -Parent) | Out-Null
    $text = Fill (Get-Content $_.FullName -Raw)
    [System.IO.File]::WriteAllText($dest, $text, (New-Object System.Text.UTF8Encoding($false)))
}

# ---- 3. gradle wrapper (shared bootstrap; distributionUrl per cell) ----
$gw = Join-Path $cell 'gradle\wrapper'
New-Item -ItemType Directory -Force -Path $gw | Out-Null
Copy-Item (Join-Path $cg 'wrapper\gradlew')            $cell -Force
Copy-Item (Join-Path $cg 'wrapper\gradlew.bat')        $cell -Force
Copy-Item (Join-Path $cg 'wrapper\gradle-wrapper.jar') $gw   -Force
(Get-Content (Join-Path $cg 'wrapper\gradle-wrapper.properties.tmpl') -Raw).Replace('%%GRADLE_DIST%%', $c.gradle) |
    Set-Content (Join-Path $gw 'gradle-wrapper.properties') -Encoding utf8NoBOM
# JDK MAJOR only, never a path: Gradle finds the installed JDK itself.
Set-Content (Join-Path $cell 'gradle\gradle-daemon-jvm.properties') -Encoding ascii -Value @(
    '#This file is generated by updateDaemonJvm', "toolchainVersion=$($c.jdk)")

# ---- 4. gen/ Java from the ONE cog source ----
$genJ = Join-Path $cell 'gen\src\main\java'
$genR = Join-Path $cell 'gen\src\main\resources'
New-Item -ItemType Directory -Force -Path $genJ | Out-Null
Copy-Item (Join-Path $cs 'common\com') $genJ -Recurse -Force
Copy-Item (Join-Path $cs 'shared\com') $genJ -Recurse -Force

# ---- 5. entrypoints: single-sourced in compat.py (D15) ----
& python (Join-Path $cg 'compat.py') $lc $genJ $c.mc
if ($LASTEXITCODE -ne 0) { throw "compat.py failed for $key" }

# ---- 6. resolve Cog blocks in the shared MC code ----
$env:PYTHONDONTWRITEBYTECODE = '1'
Get-ChildItem $genJ -Recurse -File -Filter *.java |
    Where-Object { (Get-Content $_.FullName -Raw) -match '\[\[\[cog' } | ForEach-Object {
        & cog -r -D ver=$($c.mc) -D loader=$lc -D codegen=$cg $_.FullName | Out-Null
        if ($LASTEXITCODE -ne 0) { throw ("cog failed: " + $_.FullName) }
    }

# ---- 7. resources + D4 pack.mcmeta ----
New-Item -ItemType Directory -Force -Path $genR | Out-Null
Copy-Item (Join-Path $cs 'resources\*') $genR -Recurse -Force
# D4: major <= 64 plain int (none here); 1.21.11 is in the resource DEAD ZONE (65..81): Fabric + NeoForge ship NO
# pack.mcmeta (both loaders synthesise it); classic Forge needs the exact range on the DATA major (94). 26.x:
# exact range pack_format = min_format = max_format = the resource major, from matrix.json.
if ($c.pack_format -ne '') {
    $pf = $c.pack_format
    ('{"pack":{"description":"Fill Map Coordinates resources","pack_format":' + $pf + ',"min_format":' + $pf + ',"max_format":' + $pf + '}}') |
        Set-Content (Join-Path $genR 'pack.mcmeta') -Encoding utf8NoBOM
}

Write-Host ("cog-gen OK: {0}/{1} (mc={2} pack_format='{3}')" -f $Loader, $Line, $c.mc, $c.pack_format)
